"""Opt-in empty current-schema copies for ordinary feature tests only.

Setup, migration, corruption and rollback tests keep their real initialization
helpers. The immutable image is generated by production migrations once per
helper instance, normally once per test process, and never persisted for reuse.
"""
from __future__ import annotations

import tempfile
import threading
from contextlib import closing
from pathlib import Path

from tests.m14_test_support import SOURCE_SKILL_ROOT
from task_governance_tool import storage


class EmptyDatabaseTemplate:
    def __init__(self):
        self._lock = threading.Lock()
        self._image = None

    def initialize(self, *, repo, db):
        target = storage.resolve_database_target(
            repo=repo, db=db, script_path=SOURCE_SKILL_ROOT / "scripts/taskgov.py")
        with self._lock:
            if self._image is None:
                with tempfile.TemporaryDirectory(prefix="taskgov-empty-schema-") as tmp:
                    path = Path(tmp) / "empty.sqlite"
                    with closing(storage.connect(path)) as connection:
                        storage.apply_migrations(connection)
                        connection.commit()
                    self._image = path.read_bytes()
            image = self._image
        target.db_path.parent.mkdir(parents=True, exist_ok=True)
        with target.db_path.open("xb") as destination:
            destination.write(image)
        # Production initialization now sees current DDL and no project rows.
        # It still owns identity, defaults, binding and database validation.
        result = storage.initialize_database(target)
        return {"project_id": target.project.project_id, "created": True,
                "schema_version": result.schema_version}


_TEMPLATE = EmptyDatabaseTemplate()
initialize_current_test_database = _TEMPLATE.initialize
